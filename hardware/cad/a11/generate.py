"""Generate one schedule for the A11 caps, guides, holders and print quantities."""

import csv
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def schedule():
    with (ROOT / "generated/controls.csv").open(newline="") as stream:
        controls = list(csv.DictReader(stream))
    buttons, knobs = [], []
    for control in controls:
        kind = control["kind"]
        x, y, width, depth = (float(control[k]) for k in ("x", "y", "w", "h"))
        if kind == "knob":
            knobs.append([control["id"], x, y, width, float(control["height"]), control["label"]])
        if kind not in ("button", "sector"):
            continue
        a, b = (float(control[k]) if control[k] else 0 for k in ("a", "b"))
        angle = (a + b) / 2 if kind == "sector" else 0
        cx = x + (width + depth) / 2 * math.cos(math.radians(angle)) if kind == "sector" else x
        cy = y + (width + depth) / 2 * math.sin(math.radians(angle)) if kind == "sector" else y
        if kind == "sector":
            mounts = [[-11.5, 0], [11.5, 0]]
        elif control["id"] in ("auto", "tap", "hold"):
            mounts = [[-10, 0], [10, 0]]
        elif control["id"] == "pad_1":
            mounts = [[-4, 7.5], [4, 7.5]]
        elif control["id"].startswith("pad_"):
            mounts = [[4, -8], [0, 7.5]]
        else:
            mounts = [[0, -7.5], [0, 7.5]]
        buttons.append(
            [
                control["id"],
                kind,
                width,
                depth,
                b - a,
                cx,
                cy,
                angle,
                mounts,
                control["label"],
            ]
        )
    assert len(buttons) == 29 and len(knobs) == 10
    return buttons, knobs


def panel_layout():
    """Derive lid cutouts and cap locations from the same editable CSV."""
    config = json.loads((ROOT / "layout.json").read_text())
    caps, openings = [], []
    with (ROOT / "generated/controls.csv").open(newline="") as stream:
        for c in csv.DictReader(stream):
            kind = c["kind"]
            x, y, width, depth = (float(c[key]) for key in ("x", "y", "w", "h"))
            a, b = (float(c[key]) if c[key] else 0 for key in ("a", "b"))
            tail = [a, b] if kind == "sector" else [float(c["height"]), 0]
            caps.append([c["id"], kind, x, y, width, depth, *tail])
            if kind == "knob":
                opening = [9.3, 9.3, 0, 0]
            elif kind == "sector":
                opening = [width + 0.6, depth - 0.6, a + 0.5, b - 0.5]
            elif kind == "lever":
                opening = [width - 4, depth - 2, 0, 0]
            else:
                opening = [width - 1, depth - 1, 0, 0]
            openings.append([c["id"], kind, x, y, *opening])
    config["openings"] = openings + config.pop("optical_openings")
    config["caps"] = caps
    return config


def main():
    sys.path.insert(0, str(ROOT.parents[2]))
    from hardware.cad.a11.integration import write_packet

    write_packet()
    buttons, knobs = schedule()
    layout = panel_layout()
    (ROOT / "generated/layout.scad").write_text(
        "// Generated by A11 generate.py from controls.csv and layout.json.\n"
        + "\n".join(key + " = " + json.dumps(value) + ";" for key, value in layout.items())
        + "\n"
    )
    text = "// Generated by generate.py. One control schedule drives all A11 geometry.\n"
    text += "buttons = " + json.dumps(buttons) + ";\n"
    text += "knobs = " + json.dumps(knobs) + ";\n"
    (ROOT / "generated/controls.scad").write_text(text)
    (ROOT / "generated/control-schedule.json").write_text(
        json.dumps({"revision": "A11", "buttons": buttons, "knobs": knobs}, indent=2) + "\n"
    )


if __name__ == "__main__":
    main()
