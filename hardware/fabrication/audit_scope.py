"""Current full-unit source inventory; does not promote historical certificates."""

import hashlib
import json
import os
from pathlib import Path

from hardware.fabrication.audit_candidate import native_evidence_errors
from hardware.fabrication.evidence_paths import recorded_path
from hardware.wiring.system import BOARDS

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[1]


def render_readiness(report):
    lines = ["# Standalone fabrication preparation", "",
        "**The complete unit is not ready for fabrication.** This inventory targets the",
        "first prototype of the full 12 V higher-headroom standalone design. B1 is separate.", "",
        "These are 15 functional roles, not a decision to manufacture 15 separate PCBs.",
        "The final physical partition and integrated assembly remain unfinished.", "",
        "The table is generated by `python -m hardware.fabrication.audit_scope` from",
        "[scope.json](scope.json). [current-readiness.json](current-readiness.json)",
        "records source hashes, saved native findings and unresolved requirements.", "",
        "| Functional role | Selected development source | DRC findings / opens / ERC findings |",
        "| --- | --- | --- |"]
    for row in report["roles"]:
        link = os.path.relpath(REPO/row["source"],ROOT)
        status = row.get("saved_native_status")
        if status and row.get("native_evidence_matches_selected_source"):
            counts = status["counts"]
            numbers = f"{counts['violations']} / {row['uncapped_open_connections']} / {counts['erc']}"
        else:
            numbers = "No PCB layout" if not row["layout_present"] else "No current source-bound native review in this inventory"
        lines.append(f"| {row['role'].replace('_',' ')} | [KiCad source]({link}) | {numbers} |")
    lines += ["", "DRC findings include warnings. A zero count does not approve the circuit,",
        "fabrication process, current capacity, thermal design, mechanical fit or assembly.",
        "All selected native reviews retain explicit rule coverage; no ignored category",
        "is used to obtain a passing result. The NF isolated-domain ground warnings",
        "remain visible; the negative reference nets have not been shorted to AGND.", "",
        "## Work remaining before prototype release", ""]
    lines += [f"- {item}." for item in report["unresolved_assembly_requirements"]]
    lines += ["", "Board-specific holds are recorded in scope.json. The missing ESS package",
        "drawing, PCB process questions and prepared supplier request are in",
        "[manufacturer-inputs.md](manufacturer-inputs.md). No supplier request or order",
        "has been sent. The converter footprint remains deliberately unassigned.", "",
        "A prototype release needs the completed design, inspected fabrication outputs",
        "and a first-article inspection/bring-up plan. Measurements of the subsequently",
        "built hardware are required for production qualification.", "",
        "## Runtime and storage", "",
        "Mac KiCad/OpenSCAD remain disabled. Native checks use the pinned, network-disabled",
        "Linux CAD container. Routing development runs bounded host geometry searches.",
        "Original projects and earlier candidates are preserved. Staging files are",
        "engineering evidence, not a manufacturing release. Bulk audio generation stays paused.", ""]
    (ROOT/"README.md").write_text("\n".join(lines))


def run():
    config = ROOT/"scope.json"
    scope = json.loads(config.read_text())
    roles = {row["role"] for row in scope["roles"]}
    assert set(BOARDS) <= roles and len(roles) == len(scope["roles"])
    sources = {str(config.relative_to(REPO)):hashlib.sha256(config.read_bytes()).hexdigest()}
    rows = []
    for row in scope["roles"]:
        source = REPO/row["source"]
        entry = dict(row,source_present=source.is_file(),source_sha256=None,saved_native_status=None)
        entry["layout_present"] = source.with_suffix(".kicad_pcb").is_file()
        if source.is_file():
            entry["source_sha256"] = hashlib.sha256(source.read_bytes()).hexdigest()
            sources[row["source"]] = entry["source_sha256"]
            if source.suffix == ".kicad_pro":
                for suffix in (".kicad_sch", ".kicad_pcb", ".kicad_dru"):
                    paired = source.with_suffix(suffix)
                    if paired.is_file():
                        sources[str(paired.relative_to(REPO))] = hashlib.sha256(paired.read_bytes()).hexdigest()
        review = row.get("native_review")
        if review:
            path = REPO/review
            data = json.loads(path.read_text())
            entry["saved_native_status"] = data["status"]
            entry["uncapped_open_connections"] = data.get("uncapped_open_connections",data.get("uncapped_missing_connections"))
            sources[review] = hashlib.sha256(path.read_bytes()).hexdigest()
            entry["native_evidence_errors"] = native_evidence_errors(source, data)
            entry["native_evidence_matches_selected_source"] = not entry["native_evidence_errors"]
            for name in ("drc.json", "erc.json"):
                report = path.parent/name
                if report.is_file():
                    sources[str(report.relative_to(REPO))] = hashlib.sha256(report.read_bytes()).hexdigest()
        entry["additional_evidence_errors"] = []
        for field in ("package_correction_review","handoff"):
            if row.get(field):
                evidence = REPO/row[field]
                data = json.loads(evidence.read_text())
                sources[row[field]] = hashlib.sha256(evidence.read_bytes()).hexdigest()
                for name,digest in data.get("source_sha256",{}).items():
                    dependency = recorded_path(name)
                    if not dependency.is_file() or hashlib.sha256(dependency.read_bytes()).hexdigest() != digest:
                        entry["additional_evidence_errors"].append(name)
        entry["ready_for_fabrication"] = False
        rows.append(entry)
    output = ROOT/"current-readiness.json"
    report = dict(profile=scope["profile"],release_tier=scope["proposed_release_tier"],
        baseline_functional_roles_preserved=sorted(BOARDS),role_count=len(rows),roles=rows,
        physical_board_partition_complete=False,missing_source_files=[r["source"] for r in rows if not r["source_present"]],
        unresolved_assembly_requirements=scope["assembly_holds"],source_sha256=sources,
        complete_fabrication_package=False,fabrication_released=False)
    output.write_text(json.dumps(report,indent=2)+"\n")
    render_readiness(report)
    print("Audited",len(rows),"functional roles; missing source files:",[r["source"] for r in rows if not r["source_present"]])


if __name__ == "__main__":
    run()
