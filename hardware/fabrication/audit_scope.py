def run():
    config = ROOT/"scope.json"
    scope = json.loads(config.read_text())
    roles = {row["role"] for row in scope["roles"]}
    assert set(BOARDS) <= roles and len(roles) == len(scope["roles"])
    sources = {str(config.relative_to(REPO)):hashlib.sha256(config.read_bytes()).hexdigest()}
    rows = []
    for row in scope["roles"]:
        source = REPO/row["source"]
        entry = dict(row,source_present=source.is_file(),source_sha256=None,saved_native_status=None)
        entry["layout_present"] = source.with_suffix(".kicad_pcb").is_file()
        if source.is_file():
            entry["source_sha256"] = hashlib.sha256(source.read_bytes()).hexdigest()
            sources[row["source"]] = entry["source_sha256"]
            if source.suffix == ".kicad_pro":
                for suffix in (".kicad_sch", ".kicad_pcb", ".kicad_dru"):
                    paired = source.with_suffix(suffix)
                    if paired.is_file():
                        sources[str(paired.relative_to(REPO))] = hashlib.sha256(paired.read_bytes()).hexdigest()
        review = row.get("native_review")
        if review:
            path = REPO/review
            data = json.loads(path.read_text())
            entry["saved_native_status"] = data["status"]
            entry["uncapped_open_connections"] = data.get("uncapped_open_connections",data.get("uncapped_missing_connections"))
            sources[review] = hashlib.sha256(path.read_bytes()).hexdigest()
            entry["native_evidence_errors"] = native_evidence_errors(source, data)
            entry["native_evidence_matches_selected_source"] = not entry["native_evidence_errors"]
            for name in ("drc.json", "erc.json"):
                report = path.parent/name
                if report.is_file():
                    sources[str(report.relative_to(REPO))] = hashlib.sha256(report.read_bytes()).hexdigest()
        entry["additional_evidence_errors"] = []
        for field in ("package_correction_review","handoff"):
            if row.get(field):
                evidence = REPO/row[field]
                data = json.loads(evidence.read_text())
                sources[row[field]] = hashlib.sha256(evidence.read_bytes()).hexdigest()
                for name,digest in data.get("source_sha256",{}).items():
                    dependency = recorded_path(name)
                    if not dependency.is_file() or hashlib.sha256(dependency.read_bytes()).hexdigest() != digest:
                        entry["additional_evidence_errors"].append(name)
        entry["ready_for_fabrication"] = False
        rows.append(entry)
    shared = scope.get("shared_audio_core")
    if shared:
        if shared.get("revision") == "AC04":
            from hardware.fabrication.audit_audio_main import check as check_audio_core
        elif shared.get("revision") == "AC03":
            from hardware.fabrication.audit_audio_ports import check as check_audio_core
        elif shared.get("revision") == "AC02":
            from hardware.fabrication.audit_audio_startup import check as check_audio_core
        else:
            from hardware.fabrication.audit_audio_core import check as check_audio_core
        shared = dict(shared)
        expected_roles = {"adc_driver","converter","dac_receiver"}
        if shared.get("revision") == "AC04":
            expected_roles |= {"input_range","output_stage","sequenced_bypass"}
        assert set(shared["member_roles"]) == expected_roles
        handoff = REPO/shared["handoff"]
        evidence = check_audio_core()
        assert json.loads(handoff.read_text()) == evidence
        sources[shared["handoff"]] = hashlib.sha256(handoff.read_bytes()).hexdigest()
        sources[shared["source"]] = hashlib.sha256((REPO/shared["source"]).read_bytes()).hexdigest()
        sources.update(evidence["source_sha256"])
        shared.update(electrical_parts=evidence["electrical_parts"],
            exported_physical_terminals=evidence["exported_physical_terminals"],
            native_ERC_findings=evidence["native_ERC_findings"],
            current_source_bound_integration_evidence_matches=True,
            layout_complete=False,physical_star_copper_checked=False,ready_for_fabrication=False)
        if shared.get("revision")=="AC04":
            from hardware.fabrication.audit_audio_main import current_interfaces

            interfaces=current_interfaces()
            shared["current_peer_interface_review"]=interfaces
            sources.update(interfaces["current_source_sha256"])
        layout=shared.get("layout_candidate")
        if layout:
            if layout.get("routing_stage") == "controls_06":
                from hardware.fabrication.audit_audio_main_analog_ok import check as check_audio_placement
            elif layout.get("routing_stage") == "controls_05":
                from hardware.fabrication.audit_audio_main_long_controls import check as check_audio_placement
            elif layout.get("routing_stage") == "controls_04":
                from hardware.fabrication.audit_audio_main_control_completion import check as check_audio_placement
            elif layout.get("routing_stage") == "settle_repack_01":
                from hardware.fabrication.audit_audio_main_settle_repack import check as check_audio_placement
            elif layout.get("routing_stage") == "watchdog_repack_01":
                from hardware.fabrication.audit_audio_main_watchdog_repack import check as check_audio_placement
            elif layout.get("routing_stage") == "controls_02":
                from hardware.fabrication.audit_audio_main_global_controls import check as check_audio_placement
            elif layout.get("routing_stage") == "supplies_06":
                from hardware.fabrication.audit_audio_main_supply_completion import check as check_audio_placement
            elif layout.get("routing_stage") == "supplies_02":
                from hardware.fabrication.audit_audio_main_supplies import check as check_audio_placement
            elif layout.get("routing_stage") == "controls_01":
                from hardware.fabrication.audit_audio_main_controls import check as check_audio_placement
            elif layout.get("routing_stage") == "ground_02":
                from hardware.fabrication.audit_audio_main_ground import check as check_audio_placement
            elif layout.get("routing_stage") == "local_cells_02":
                from hardware.fabrication.audit_audio_main_routes import check as check_audio_placement
            else:
                from hardware.fabrication.audit_audio_main_placement import check as check_audio_placement

            layout=dict(layout)
