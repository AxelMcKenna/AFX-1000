"""Index current hardware selections and retained trials without moving sealed evidence."""

import argparse
import json
import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FAB = ROOT / "hardware/fabrication"


def catalog():
    # Index the saved work, excluding unrelated candidates still being edited.
    names = subprocess.check_output(
        ["git", "ls-files", "--cached", "-z", "--", "hardware/fabrication/staging"], cwd=ROOT,
    ).decode().split("\0")
    statuses = [ROOT / name for name in names
                if Path(name).name == "status.json"
                and Path(name).parent.name.startswith("two-board-fabrication-status-")]
    latest = max(statuses, key=lambda p: int(p.parent.name.rsplit("-", 1)[1]))
    status = json.loads(latest.read_text())
    scope = json.loads((FAB / "scope.json").read_text())
    selected = {str(Path(status[k]).parent) for k in ("signal_project", "power_project")}
    references = {str(Path(r["source"]).parent) for r in scope["roles"]}
    support = {str(latest.parent.relative_to(ROOT))}
    support.update(str(Path(p).parent) for p in status["source_sha256"])
    groups = defaultdict(list)
    for name in names:
        if name:
            groups["/".join(Path(name).parts[:4])].append(name)
    entries = []
    for directory, files in sorted(groups.items()):
        category = (
            "current-design" if directory in selected else
            "module-reference" if directory in references else
            "current-review-input" if directory in support else
            "retained-history-or-experiment"
        )
        entries.append({
            "path": directory,
            "category": category,
            "files": len(files),
            "bytes": sum((ROOT / name).stat().st_size for name in files),
        })
    return {
        "scope": "Tracked-file navigation inventory; categories are not fabrication approval or fresh validation.",
        "status": str(latest.relative_to(ROOT)),
        "revision": status["revision"],
        "signal_project": status["signal_project"],
        "power_project": status["power_project"],
        "fabrication_released": status["fabrication_released"],
        "entries": entries,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the saved catalog without writing")
    args = parser.parse_args()
    result = catalog()
    lines = ["# Retained hardware history and experiments", "",
             "Generated by `python -m tools.artifacts.catalog_hardware`. These are unselected",
             "snapshots, searches and historical inputs, not fabrication sources. Rejected",
             "trials remain available because later reviews may bind their exact bytes.", "",
             "See [current designs](../active/README.md) and the",
             "[complete catalog](../workspace-catalog.json) for other categories.", "",
             "| Candidate | Files | MiB |", "| --- | ---: | ---: |"]
    for entry in result["entries"]:
        if entry["category"] != "retained-history-or-experiment":
            continue
        directory = Path(entry["path"])
        destination = f"../staging/{directory.name}/"
        if (ROOT / directory / "README.md").is_file():
            destination += "README.md"
        lines.append(f"| [{directory.name}]({destination}) | {entry['files']} | {entry['bytes'] / 1024**2:.2f} |")
    outputs = {
        FAB / "workspace-catalog.json": json.dumps(result, indent=2) + "\n",
        FAB / "experiments/INDEX.md": "\n".join(lines) + "\n",
    }
    for target, content in outputs.items():
        if args.check:
            if not target.is_file() or target.read_text() != content:
                parser.exit(1, "Hardware catalog is stale; regenerate with this module.\n")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
    print(f"{result['revision']}: {len(result['entries'])} candidate directories indexed")


if __name__ == "__main__":
    main()
