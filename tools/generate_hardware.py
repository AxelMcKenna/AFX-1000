#!/usr/bin/env python3
"""Generate a common mechanical/electrical drawing and firmware pin contract."""
import argparse, csv, html, io, json, math, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def validate(d):
    e=d['enclosure']; controls=d['controls']; ids=[c['id'] for c in controls]
    assert len(ids)==len(set(ids)), 'Duplicate component ID'
    pins=list(d['pins'].values()); assert len(pins)==len(set(pins)), 'GPIO conflict'
    assert not set(pins)&set(d['reserved_sdmmc_pins']), 'GPIO conflicts with SDMMC'
    assert len(d['adc_params'])<=16
    assert sorted(c['channel'] for c in controls if c['kind']=='button')==list(range(29))
    shapes=[]
    for c in controls:
        w,h=c.get('keepout',[c['w'],c['h']]); x,y=c['x'],c['y']
        assert x-w/2>=e['wall'] and x+w/2<=e['width']-e['wall'], c['id']+' crosses side wall'
        assert y-h/2>=e['wall'] and y+h/2<=e['depth']-e['wall'], c['id']+' crosses end wall'
        shapes.append((c['id'],x,y,w,h,c['shape']))
    def intersects(a,b):
        _,x,y,w,h,shape=a; _,xx,yy,ww,hh,other=b
        dx,dy=abs(x-xx),abs(y-yy)
        if shape==other=='circle':return math.hypot(dx,dy)<(w+ww)/2+1
        if shape==other=='rect':return dx<(w+ww)/2+1 and dy<(h+hh)/2+1
        if shape=='rect':return intersects(b,a)
        return math.hypot(max(0,dx-ww/2),max(0,dy-hh/2))<w/2+1
    for i,a in enumerate(shapes):
        for b in shapes[i+1:]:assert not intersects(a,b), f'Component clearance: {a[0]} / {b[0]}'
    for x,y in e['posts']:
        a=('post',x,y,9,9,'circle')
        for b in shapes:assert not intersects(a,b), 'Screw boss / '+b[0]
    for p in d['rear_ports']:
        assert p['x']-p['w']/2>e['wall'] and p['x']+p['w']/2<e['width']-e['wall']
        assert p['z']-p.get('h',p['w'])/2>e['wall'] and p['z']+p.get('h',p['w'])/2<e['tray_height']-2

def artifacts(d):
    e=d['enclosure']; out={}
    scad=['// Generated by tools/generate_hardware.py; edit hardware/prototype.json.']
    scad += [f'{k}={json.dumps(v)};' for k,v in e.items() if k!='height']
    scad+=['module panel_cutouts() {']
    for c in d['controls']:
        primitive=f"circle(d={c['w']});" if c['shape']=='circle' else f"square([{c['w']},{c['h']}],center=true);"
        scad.append(f"  translate([{c['x']},{c['y']}]) {primitive} // {c['id']}")
    scad+=['  for(p=posts) translate(p) circle(d=screw_diameter);','}','module rear_cutouts() {']
    for p in d['rear_ports']:
        primitive=f"cylinder(h=wall+2,d={p['w']});" if p['shape']=='circle' else f"translate([-{p['w']/2},-{p['h']/2},0]) cube([{p['w']},{p['h']},wall+2]);"
        scad.append(f"  translate([{p['x']},depth+1,{p['z']}]) rotate([90,0,0]) {primitive}")
    scad+=['}','module knob_envelopes() {']
    for c in d['controls']:
        if c['kind']=='pot':scad.append(f"  color(\"#fcad45\") translate([{c['x']},{c['y']},0]) cylinder(h={20 if c['id']=='scene' else 16},d={c['keepout'][0]});")
    scad+=['}'];out['panel_geometry.scad']='\n'.join(scad)+'\n'
    # DXF R12 entities are millimetres; Y is inverted to match the CAD bottom-left origin.
    entities=[]
    def line(x1,y1,x2,y2):entities.extend(['0','LINE','8','CUT','10',str(x1),'20',str(e['depth']-y1),'11',str(x2),'21',str(e['depth']-y2)])
    def circle(x,y,r):entities.extend(['0','CIRCLE','8','CUT','10',str(x),'20',str(e['depth']-y),'40',str(r)])
    def rect(x,y,w,h):
        pts=[(x-w/2,y-h/2),(x+w/2,y-h/2),(x+w/2,y+h/2),(x-w/2,y+h/2)]
        for a,b in zip(pts,pts[1:]+pts[:1]):line(*a,*b)
    # Match the rounded OpenSCAD outline exactly, rather than a bounding rectangle.
    w,h,r=e['width'],e['depth'],e['corner_radius']
    line(r,0,w-r,0);line(w,r,w,h-r);line(w-r,h,r,h);line(0,h-r,0,r)
    for x,y,start,end in [(r,r,180,270),(w-r,r,270,360),(w-r,h-r,0,90),(r,h-r,90,180)]:
        # Arc angles are Cartesian; invert Y and orientation of the drawing.
        entities.extend(['0','ARC','8','CUT','10',str(x),'20',str(h-y),'40',str(r),'50',str((360-end)%360),'51',str((360-start)%360)])
    for c in d['controls']:
        if c['shape']=='circle':circle(c['x'],c['y'],c['w']/2)
        else:rect(c['x'],c['y'],c['w'],c['h'])
    for x,y in e['posts']:circle(x,y,e['screw_diameter']/2)
    out['panel.dxf']='\n'.join(['0','SECTION','2','HEADER','9','$INSUNITS','70','4','0','ENDSEC','0','SECTION','2','ENTITIES']+entities+['0','ENDSEC','0','EOF'])+'\n'
    svg=[f'<svg xmlns="http://www.w3.org/2000/svg" width="1670" height="785" viewBox="0 0 {w} {h}">',f'<rect x="0" y="0" width="{w}" height="{h}" rx="{r}" fill="#20262e"/>','<g font-family="Arial,sans-serif" text-anchor="middle">']
    for c in d['controls']:
        x,y=c['x'],c['y']; color='#ffb54b' if c['kind']=='pot' else '#49d4d7'
        if 'keepout' in c:
            cw,ch=c['keepout']
            if c['shape']=='circle':svg.append(f'<circle cx="{x}" cy="{y}" r="{cw/2}" fill="none" stroke="{color}" stroke-width=".4"/>')
            else:svg.append(f'<rect x="{x-cw/2}" y="{y-ch/2}" width="{cw}" height="{ch}" rx="1" fill="none" stroke="{color}" stroke-width=".4"/>')
        if c['shape']=='circle':svg.append(f'<circle cx="{x}" cy="{y}" r="{c["w"]/2}" fill="#080c12" stroke="#8794a3" stroke-width=".3"/>')
        else:svg.append(f'<rect x="{x-c["w"]/2}" y="{y-c["h"]/2}" width="{c["w"]}" height="{c["h"]}" fill="#080c12" stroke="#8794a3" stroke-width=".3"/>')
        labely=y+c.get('keepout',[c['w'],c['h']])[1]/2+3
        svg.append(f'<text x="{x}" y="{labely}" fill="{color}" font-size="2.1">{html.escape(c["label"])}</text>')
    for x,y in e['posts']:svg.append(f'<circle cx="{x}" cy="{y}" r="1.7" fill="#080c12" stroke="#8794a3" stroke-width=".3"/>')
    svg+=['<text x="24" y="9" fill="#c4cedb" font-size="3">RMX · A0</text>','<text x="167" y="151" fill="#92a4b8" font-size="2.3">334 × 157 mm · fit prototype · verify parts before fabrication</text>','</g></svg>']
    out['panel.svg']='\n'.join(svg)+'\n'
    csvout=io.StringIO();writer=csv.writer(csvout,lineterminator="\n");writer.writerow(['id','kind','x_mm','y_mm','cutout_width_mm','cutout_height_mm','channel'])
    for c in d['controls']:writer.writerow([c['id'],c['kind'],c['x'],c['y'],c['w'],c['h'],c.get('channel','')])
    out['panel_coordinates.csv']=csvout.getvalue()
    hdr=['// Generated. Do not edit.','#pragma once','#include "rmx/Parameters.h"','namespace rmx::board {']
    hdr += [f'inline constexpr unsigned {key}={value};' for key,value in d['pins'].items()]
    hdr += ['inline constexpr Param adcParameters[]={'+','.join('Param::'+p for p in d['adc_params'])+'};','inline constexpr unsigned buttonCount=29;','inline constexpr unsigned releaseBackBit=29,releaseBrakeBit=30,userBit=31;','}']
    out['BoardConfig.h']='\n'.join(hdr)+'\n'
    return out

def preview(d,path):
    from PIL import Image,ImageDraw,ImageFont
    scale=5;e=d['enclosure'];im=Image.new('RGB',(e['width']*scale,e['depth']*scale),'#20262e');draw=ImageDraw.Draw(im)
    font=ImageFont.truetype('/System/Library/Fonts/Supplemental/Arial.ttf',10)
    for c in d['controls']:
        x,y=c['x']*scale,c['y']*scale;color='#ffb54b' if c['kind']=='pot' else '#49d4d7'
        def shape(w,h,fill,outline):
            box=(x-w*scale/2,y-h*scale/2,x+w*scale/2,y+h*scale/2)
            if c['shape']=='circle':draw.ellipse(box,fill=fill,outline=outline,width=2)
            else:draw.rectangle(box,fill=fill,outline=outline,width=2)
        if 'keepout' in c:shape(*c['keepout'],None,color)
        shape(c['w'],c['h'],'#080c12','#8794a3')
        draw.text((x,y+c.get('keepout',[c['w'],c['h']])[1]*scale/2+4),c['label'],font=font,anchor='mt',fill=color)
    for x,y in e['posts']:draw.ellipse((x*scale-8,y*scale-8,x*scale+8,y*scale+8),fill='#080c12',outline='#8794a3')
    draw.text((20,20),'RMX / A0 FIT PROTOTYPE',font=font,fill='white')
    draw.text((835,750),'334 x 157 mm / component positions require measurement',anchor='mt',font=font,fill='#92a4b8');im.save(path)

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');parser.add_argument('--preview',action='store_true');args=parser.parse_args()
    d=json.loads((ROOT/'hardware/prototype.json').read_text());validate(d)
    dest=ROOT/'hardware/generated';dest.mkdir(parents=True,exist_ok=True)
    for name,data in artifacts(d).items():
        path=dest/name
        if args.check:
            assert path.exists() and path.read_text()==data, f'Stale generated artifact: {name}'
        else:path.write_text(data)
    if args.preview:preview(d,dest/'panel.png')
    print(f'PASS: {len(d["controls"])} panel features, clearances, mounting bosses, GPIO/SD reservation, generated file consistency')
if __name__=='__main__':main()
